-- ============================================================
-- Migration 000: local PostgreSQL shim (NOT for Supabase)
-- ============================================================
-- Run ONLY on a plain local PostgreSQL (DB_BACKEND=postgres), before
-- db_schema.sql. Never run it on the Supabase project: Supabase already has
-- everything below, and `photos` there belongs to the RoadSide app.
--
-- db_schema.sql and migrations 001-004 were written for Supabase and depend on
-- four things a plain PostgreSQL does not have. This file adds the minimum so
-- they run UNCHANGED (the point: one schema, two hosts):
--   1. schema `auth` with table auth.users(id uuid pk)  - FK target of
--      assessments.user_id / reviewed_by and custom_distress_types.added_by
--   2. functions auth.uid() / auth.role()                - used by the RLS policies
--   3. roles anon / authenticated / service_role         - named in GRANTs and policies
--   4. table `photos`                                    - created by the RoadSide app on
--      Supabase (by no migration); migration 002 adds its FK and trigger
--
-- `photos` copies the live table column for column (read from the Supabase
-- PostgREST OpenAPI on 2026-10-27; scripts/tests/test_local_db.py checks the
-- local schema against that file). `id` is an identity column: the app inserts
-- without an id, and Supabase's table editor creates bigint identity keys.
--
-- auth.uid() / auth.role() read the same request settings Supabase's do. On
-- the local server nobody sets them, so they return NULL: the policies then
-- grant nothing to anon/authenticated, and the app connects as the table
-- owner, which RLS does not restrict (same effect as Supabase's service key).
--
-- Idempotent: every statement is guarded, so re-running changes nothing.
-- ============================================================

BEGIN;

-- 1. auth schema + users -------------------------------------------------
CREATE SCHEMA IF NOT EXISTS auth;

CREATE TABLE IF NOT EXISTS auth.users (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid()
);

-- 2. auth.uid() / auth.role() ----------------------------------------------
CREATE OR REPLACE FUNCTION auth.uid()
RETURNS UUID
LANGUAGE sql
STABLE
AS $$
    SELECT NULLIF(
        COALESCE(
            current_setting('request.jwt.claim.sub', true),
            (NULLIF(current_setting('request.jwt.claims', true), '')::jsonb ->> 'sub')
        ), ''
    )::uuid
$$;

CREATE OR REPLACE FUNCTION auth.role()
RETURNS TEXT
LANGUAGE sql
STABLE
AS $$
    SELECT NULLIF(
        COALESCE(
            current_setting('request.jwt.claim.role', true),
            (NULLIF(current_setting('request.jwt.claims', true), '')::jsonb ->> 'role')
        ), ''
    )::text
$$;

-- 3. Supabase API roles (no login; the app never connects as them) --------
DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'anon') THEN
        CREATE ROLE anon NOLOGIN NOINHERIT;
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'authenticated') THEN
        CREATE ROLE authenticated NOLOGIN NOINHERIT;
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'service_role') THEN
        CREATE ROLE service_role NOLOGIN NOINHERIT BYPASSRLS;
    END IF;
END
$$;

GRANT USAGE ON SCHEMA auth TO anon, authenticated, service_role;
GRANT EXECUTE ON FUNCTION auth.uid() TO anon, authenticated, service_role;
GRANT EXECUTE ON FUNCTION auth.role() TO anon, authenticated, service_role;

-- 4. photos (RoadSide app's table, identical columns to the live one) -----
CREATE TABLE IF NOT EXISTS photos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    image_url TEXT NOT NULL,
    address TEXT DEFAULT '',
    latitude DOUBLE PRECISION,
    longitude DOUBLE PRECISION,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    captured_at TIMESTAMPTZ
);

COMMENT ON COLUMN photos.captured_at IS
    'Original photo capture time when known. NULL means unavailable; created_at remains upload time.';

COMMIT;
